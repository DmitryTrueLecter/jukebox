// Regenerates src/api/schema.d.ts from the FastAPI app (no running server needed).
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const venvPython = path.join(root, ".venv", process.platform === "win32" ? "Scripts/python.exe" : "bin/python");
const python = process.env.PYTHON ?? (existsSync(venvPython) ? venvPython : "python3");

const schema = JSON.parse(execFileSync(python, [path.join(root, "scripts", "dump_openapi.py")], { encoding: "utf8" }));
const out = path.join(root, "frontend", "src", "api", "schema.d.ts");
writeFileSync(out, "// Generated by `npm run gen:api` from server.py. Do not edit.\n" + astToString(await openapiTS(schema)));
console.log("wrote", path.relative(process.cwd(), out));